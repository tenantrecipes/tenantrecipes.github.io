"""Check every internal href/src in dist/ resolves to a file (and #anchors exist). Exit 1 on broken links."""
import re, sys, pathlib
from urllib.parse import urlsplit, unquote
DIST = pathlib.Path(__file__).resolve().parent.parent / "dist"
broken, checked = [], 0
ids = {}
for f in DIST.rglob("*.html"):
    ids[f] = set(re.findall(r'\bid="([^"]+)"', f.read_text()))
for f in DIST.rglob("*.html"):
    if f.name == "404.html":
        continue
    for ref in re.findall(r'(?:href|src)="([^"]+)"', f.read_text()):
        if re.match(r"^(https?:|mailto:|data:)", ref):
            continue
        checked += 1
        u = urlsplit(ref)
        target = f if not u.path else (f.parent / unquote(u.path)).resolve()
        if target.is_dir():
            target = target / "index.html"
        if not target.exists() or DIST.resolve() not in target.resolve().parents and target.resolve() != DIST.resolve():
            broken.append(f"{f.relative_to(DIST)} -> {ref}"); continue
        if u.fragment and target.suffix == ".html" and u.fragment not in ids.get(target, set()):
            broken.append(f"{f.relative_to(DIST)} -> {ref} (missing #{u.fragment})")
# card links generated by app.js
js = (DIST / "data/recipes.js").read_text()
for rid in re.findall(r'"id": "([^"]+)"', js):
    checked += 1
    if not (DIST / "recipes" / f"{rid}.html").exists():
        broken.append(f"app.js card -> recipes/{rid}.html")
print(f"Checked {checked} internal links: {len(broken)} broken")
for b in broken:
    print("  BROKEN", b)
sys.exit(1 if broken else 0)
